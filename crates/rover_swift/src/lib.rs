/// SQLite-backed storage for clipboard history and key-value settings.
///
/// Uses WAL journal mode for fast concurrent access.
/// Opens (or creates) the database in `~/Library/Application Support/dev.undivisible.Rover/`.
#[derive(eqswift::Object)]
pub struct RoverDatabase {
    db: Arc<RoverDb>,
}

#[eqswift::export]
impl RoverDatabase {
    /// Open or create the Rover database.
    #[uniffi::constructor]
    pub fn open() -> Result<Arc<Self>, RoverError> {
        let opts = RoverDbOptions {
            allow_unencrypted: true,
        };
        let db = RoverDb::open_with_options(opts).map_err(RoverError::from_anyhow)?;
        Ok(Arc::new(Self { db: Arc::new(db) }))
    }

    // ── Clipboard ────────────────────────────────────────────────────────────

    /// Append a clipboard entry (deduplication handled by the DB layer).
    pub fn push_clipboard(&self, text: String) -> Result<(), RoverError> {
        self.db
            .add_clipboard_entry(&text)
            .map_err(RoverError::from_anyhow)
    }

    /// Return all clipboard entries, newest first.
    pub fn clipboard_history(&self) -> Result<Vec<ClipboardEntry>, RoverError> {
        self.db
            .list_clipboard_history()
            .map_err(RoverError::from_anyhow)
            .map(|rows| {
                rows.into_iter()
                    .map(|e| ClipboardEntry {
                        id: e.id,
                        content: e.content,
                        timestamp: e.timestamp,
                    })
                    .collect()
            })
    }

    /// Delete one clipboard entry by id.
    pub fn delete_clipboard(&self, id: i64) -> Result<(), RoverError> {
        self.db
            .delete_clipboard_entry(id)
            .map_err(RoverError::from_anyhow)
    }

    /// Delete all clipboard entries.
    pub fn clear_clipboard(&self) -> Result<(), RoverError> {
        self.db
            .clear_clipboard_history()
            .map_err(RoverError::from_anyhow)
    }

    // ── Settings ─────────────────────────────────────────────────────────────

    /// Read a setting. Returns `nil` if not set.
    pub fn get_setting(&self, key: String) -> Result<Option<String>, RoverError> {
        self.db.get_setting(&key).map_err(RoverError::from_anyhow)
    }

    /// Write a setting.
    pub fn set_setting(&self, key: String, value: String) -> Result<(), RoverError> {
        self.db
            .set_setting(&key, &value)
            .map_err(RoverError::from_anyhow)
    }

    // ── Query history ─────────────────────────────────────────────────────────

    /// Push a query to history (max 100 entries, oldest auto-pruned).
    pub fn push_query_history(&self, query: String) -> Result<(), RoverError> {
        self.db
            .push_query_history(&query)
            .map_err(RoverError::from_anyhow)
    }

    /// Return the last `limit` queries, newest first.
    pub fn list_query_history(&self, limit: u32) -> Result<Vec<String>, RoverError> {
        self.db
            .list_query_history_limited(limit as usize)
            .map_err(RoverError::from_anyhow)
    }

    // ── AI audit log ──────────────────────────────────────────────────────────

    /// Log an AI tool call for audit purposes.
    pub fn log_ai_audit(
        &self,
        tool_name: String,
        args_json: String,
        result: String,
    ) -> Result<(), RoverError> {
        self.db
            .log_ai_audit(&tool_name, &args_json, &result)
            .map_err(RoverError::from_anyhow)
    }
}

/// One clipboard history entry.
#[derive(eqswift::Record, Clone)]
pub struct ClipboardEntry {
    pub id: i64,
    pub content: String,
    /// Unix timestamp (seconds since epoch).
    pub timestamp: i64,
}

