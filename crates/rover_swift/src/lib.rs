/// On-device semantic search using fastembed embeddings (AllMiniLML6V2, ~33 MB).
///
/// Documents are stored in a WAL-mode SQLite DB alongside 384-dim f32 embeddings.
/// An in-memory cache keeps all embeddings resident so searches are O(n) cosine
/// similarity with zero disk I/O.
///
/// **Initialisation blocks** while the model loads (~1–3 s on first run, instant
/// on subsequent runs once weights are cached). Always call `SemanticSearch.open()`
/// from a background thread, never from the main actor.
#[derive(eqswift::Object)]
pub struct SemanticSearch {
    index: Arc<Mutex<rover_semantic::SemanticIndex>>,
}

#[eqswift::export]
impl SemanticSearch {
    /// Open or create the semantic index.
    /// Blocks while the embedding model loads — call off the main thread.
    #[uniffi::constructor]
    pub fn open() -> Result<Arc<Self>, RoverError> {
        let path = semantic_db_path().map_err(RoverError::from_anyhow)?;
        let index = rover_semantic::SemanticIndex::new(&path).map_err(RoverError::from_anyhow)?;
        Ok(Arc::new(Self { index: Arc::new(Mutex::new(index)) }))
    }

    // ── Indexing ─────────────────────────────────────────────────────────────

    /// Index (or re-index) a single document.
    ///
    /// - `id`: stable unique key (e.g. app bundle ID, file path, clipboard entry ID).
    /// - `collection`: logical group: `"apps"`, `"files"`, `"clipboard"`, `"commands"`.
    /// - `text`: the content to embed.
    pub fn upsert(
        &self,
        id: String,
        collection: String,
        text: String,
    ) -> Result<(), RoverError> {
        self.index
            .lock()
            .unwrap()
            .upsert(&id, &collection, &text, serde_json::Value::Null)
            .map_err(RoverError::from_anyhow)
    }

    /// Batch-index multiple documents in one embedding call (more efficient than
    /// calling `upsert` in a loop).
    pub fn upsert_batch(&self, docs: Vec<SemanticDoc>) -> Result<(), RoverError> {
        let batch: Vec<(String, String, String, serde_json::Value)> = docs
            .into_iter()
            .map(|d| (d.id, d.collection, d.text, serde_json::Value::Null))
            .collect();
        self.index
            .lock()
            .unwrap()
            .upsert_batch(&batch)
            .map_err(RoverError::from_anyhow)
    }

    /// Remove a document by id.
    pub fn remove(&self, id: String) -> Result<(), RoverError> {
        self.index.lock().unwrap().remove(&id).map_err(RoverError::from_anyhow)
    }

    /// Remove all documents in a collection.
    pub fn clear_collection(&self, collection: String) -> Result<(), RoverError> {
        self.index
            .lock()
            .unwrap()
            .clear_collection(&collection)
            .map_err(RoverError::from_anyhow)
    }

    // ── Querying ─────────────────────────────────────────────────────────────

    /// Return the `top_k` most semantically similar documents to `query`.
    /// Pass an empty string for `collection` to search all collections.
    pub fn search(
        &self,
        query: String,
        collection: String,
        top_k: u32,
    ) -> Result<Vec<SemanticResult>, RoverError> {
        let col = if collection.is_empty() { None } else { Some(collection.as_str()) };
        self.index
            .lock()
            .unwrap()
            .search(&query, col, top_k as usize)
            .map_err(RoverError::from_anyhow)
            .map(|results| {
                results
                    .into_iter()
                    .map(|r| SemanticResult {
                        id: r.id,
                        collection: r.collection,
                        text: r.text,
                        score: r.score,
                    })
                    .collect()
            })
    }

    /// Number of indexed documents.
    pub fn count(&self) -> u32 {
        self.index.lock().unwrap().len() as u32
    }
}

/// A document to batch-index via `SemanticSearch.upsertBatch`.
#[derive(eqswift::Record, Clone)]
pub struct SemanticDoc {
    pub id: String,
    pub collection: String,
    pub text: String,
}

/// One semantic search hit.
#[derive(eqswift::Record, Clone)]
pub struct SemanticResult {
    pub id: String,
    pub collection: String,
    pub text: String,
    /// Cosine similarity score in [-1, 1]. Higher is more relevant.
    pub score: f32,
}

// ── Helpers ───────────────────────────────────────────────────────────────────

fn semantic_db_path() -> anyhow::Result<std::path::PathBuf> {
    let support = dirs::data_local_dir()
        .or_else(|| {
            std::env::var("HOME")
                .ok()
                .map(|h| std::path::PathBuf::from(h).join("Library/Application Support"))
        })
        .ok_or_else(|| anyhow::anyhow!("cannot determine app support directory"))?;
    let dir = support.join("dev.undivisible.Rover");
    std::fs::create_dir_all(&dir)?;
    Ok(dir.join("semantic.db"))
}

