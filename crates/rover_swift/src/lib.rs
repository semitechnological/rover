/// Returns `true` if Apple Intelligence (FoundationModels) is available and ready
/// on this device. Cheap synchronous check — safe to call on any thread.
#[uniffi::export]
pub fn ai_is_available() -> bool {
    rs_ai_local::foundationmodels::is_available()
}

// ══════════════════════════════════════════════════════════════════════════════
// MARK: - Error type
// ══════════════════════════════════════════════════════════════════════════════

/// Unified error type for all fallible Rover backend operations.
#[derive(eqswift::Error, Debug, thiserror::Error)]
pub enum RoverError {
    #[error("{message}")]
    Internal { message: String },
}

impl RoverError {
    fn from_anyhow(e: impl std::fmt::Display) -> Self {
        Self::Internal { message: e.to_string() }
    }
}
