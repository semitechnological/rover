/// Unified error type for all fallible Rover backend operations.
#[derive(eqswift::Error, Debug, thiserror::Error)]
pub enum RoverError {
    #[error("{message}")]
    Internal { message: String },
}

impl RoverError {
    fn from_anyhow(e: impl std::fmt::Display) -> Self {
        Self::Internal {
            message: e.to_string(),
        }
    }
}
