//! # Rover Unified Swift Backend
//!
//! Single Rust dylib that the SwiftUI frontend links to.
//! Exports four capability groups to Swift via eqswift / UniFFI:
//!
//! | Group        | Swift type(s)               | What it does                          |
//! |---|---|---|
//! | Fuzzy        | `FuzzyEngine`               | skim/rayon parallel scorer            |
//! | Database     | `RoverDatabase`             | SQLite clipboard history + settings   |
//! | Semantic     | `SemanticSearch`            | fastembed vector search               |
//! | Intelligence | `ai_is_available()` (fn)    | Apple Intelligence availability check |
//!
//! Swift only ever imports one file — `rover_swift.swift` — generated by
//! `build-swiftui.sh`. Internal workspace crates are invisible to Swift.

use rover_db::{RoverDb, RoverDbOptions};
use rover_fuzzy::{match_strings, normalize_query, StringMatchCandidate};
use std::sync::{Arc, Mutex};

eqswift::setup!();

// ══════════════════════════════════════════════════════════════════════════════
// MARK: - Fuzzy scoring
// ══════════════════════════════════════════════════════════════════════════════

/// Parallel skim-algorithm fuzzy scorer.
///
/// Backed by rayon so all available cores are used when ranking candidates.
/// Allocate once and reuse — `FuzzyEngine` is stateless.
#[derive(eqswift::Object, Default)]
pub struct FuzzyEngine;

#[eqswift::export]
impl FuzzyEngine {
    #[uniffi::constructor]
    pub fn new() -> Self {
        Self
    }

    /// Score and rank `candidates` against `query`, best-first.
    /// Non-matching candidates are excluded from the result.
    pub fn rank(&self, query: String, candidates: Vec<String>) -> Vec<RankedItem> {
        let normalised = normalize_query(&query);
        let input: Vec<StringMatchCandidate> = candidates
            .iter()
            .enumerate()
            .map(|(i, s)| StringMatchCandidate::new(i, s))
            .collect();

        match_strings(&input, &normalised, candidates.len())
            .into_iter()
            .map(|m| RankedItem {
                candidate: candidates[m.candidate_id].clone(),
                score: m.score,
            })
            .collect()
    }
}

/// One scored result from `FuzzyEngine.rank`.
#[derive(eqswift::Record, Clone)]
pub struct RankedItem {
    pub candidate: String,
    /// Skim score — higher is better. Typical range 0–10 000.
    pub score: i64,
}

